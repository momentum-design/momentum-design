const fs = require('node:fs');
const path = require('node:path');

const OUTPUT_PATH = path.resolve(__dirname, '../src/data/assets.registry.ts');
const REPO_ROOT = path.resolve(__dirname, '../../../..');

const ASSET_SOURCES = [
  {
    kind: 'icon',
    packageName: '@momentum-design/icons',
    rootPath: path.resolve(__dirname, '../../../assets/icons/src'),
    extensions: ['.svg'],
    outputDirectory: () => 'svg',
    normalizeName: true,
  },
  {
    kind: 'illustration',
    packageName: '@momentum-design/illustrations',
    rootPath: path.resolve(__dirname, '../../../assets/illustrations/src'),
    extensions: ['.svg'],
    outputDirectory: () => 'svg',
    normalizeName: true,
  },
  {
    kind: 'brand-visual',
    packageName: '@momentum-design/brand-visuals',
    rootPath: path.resolve(__dirname, '../../../assets/brand-visuals/src'),
    extensions: ['.png', '.svg'],
    outputDirectory: extension => extension.slice(1),
    normalizeName: true,
  },
  {
    kind: 'animation',
    packageName: '@momentum-design/animations',
    rootPath: path.resolve(__dirname, '../../../assets/animations/src'),
    extensions: ['.json', '.svg'],
    outputDirectory: (_extension, category) => category,
    normalizeName: false,
    preserveRelativeOutput: true,
  },
];

function walkFiles(directoryPath) {
  if (!fs.existsSync(directoryPath)) {
    return [];
  }

  return fs
    .readdirSync(directoryPath, { withFileTypes: true })
    .flatMap(dirent => {
      const itemPath = path.join(directoryPath, dirent.name);

      if (dirent.isDirectory()) {
        return walkFiles(itemPath);
      }

      return dirent.isFile() ? [itemPath] : [];
    });
}

function toPackageAssetName(fileName, normalizeName) {
  const parsed = path.parse(fileName);
  const assetName = normalizeName ? parsed.name.replace(/[_\s]+/g, '-') : parsed.name;

  return assetName.toLowerCase();
}

function buildKeywords(entry) {
  return [
    entry.name,
    entry.kind,
    entry.category,
    entry.format,
    entry.packageName,
    path.basename(entry.sourcePath),
  ]
    .join(' ')
    .toLowerCase()
    .split(/[^a-z0-9]+/)
    .filter(Boolean)
    .filter((keyword, index, all) => all.indexOf(keyword) === index)
    .sort();
}

function buildEntry(sourceConfig, filePath) {
  const relativeSourcePath = path.relative(sourceConfig.rootPath, filePath);
  const segments = relativeSourcePath.split(path.sep);
  const category = segments[0];
  const extension = path.extname(filePath);
  const format = extension.slice(1);
  const name = toPackageAssetName(path.basename(filePath), sourceConfig.normalizeName);
  const outputDirectory = sourceConfig.preserveRelativeOutput
    ? path.dirname(relativeSourcePath).split(path.sep).join('/')
    : sourceConfig.outputDirectory(extension, category);

  const entry = {
    name,
    kind: sourceConfig.kind,
    packageName: sourceConfig.packageName,
    category,
    format,
    sourcePath: path.relative(REPO_ROOT, filePath),
    importPath: `${sourceConfig.packageName}/dist/${outputDirectory}/${name}.${format}`,
  };

  return {
    ...entry,
    keywords: buildKeywords(entry),
  };
}

function main() {
  const entries = ASSET_SOURCES.flatMap(sourceConfig => (
    walkFiles(sourceConfig.rootPath)
      .filter(filePath => sourceConfig.extensions.includes(path.extname(filePath)))
      .map(filePath => buildEntry(sourceConfig, filePath))
  )).sort((a, b) => (
    a.kind.localeCompare(b.kind)
    || a.category.localeCompare(b.category)
    || a.name.localeCompare(b.name)
  ));
  const jsonChunks = JSON.stringify(entries, null, 2)
    .match(/[\s\S]{1,16000}/g)
    .map(chunk => JSON.stringify(chunk))
    .join(',\n  ');

  const output = `// Generated by scripts/generate-asset-registry.js. Do not edit manually.
import type { AssetRegistryEntry } from './registry.types';

const assetsRegistryJson: string = [
  ${jsonChunks},
].join('');

const assetsRegistry = JSON.parse(assetsRegistryJson) as AssetRegistryEntry[];

export default assetsRegistry;
`;

  fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(OUTPUT_PATH, output);
  console.log(`Generated ${entries.length} asset registry entries.`);
}

main();
